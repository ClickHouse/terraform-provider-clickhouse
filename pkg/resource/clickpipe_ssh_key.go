func (r *ClickPipeSSHKeyResource) Configure(ctx context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	// Prevent panic if the provider has not been configured.
	if req.ProviderData == nil {
		return
	}

	client, ok := req.ProviderData.(*api.ClientImpl)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Resource Configure Type",
			fmt.Sprintf("Expected *api.ClientImpl, got: %T. Please report this issue to the provider developers.", req.ProviderData),
		)
		return
	}

	r.client = client
}

func applySSHKeyToModel(serviceID string, sshKey *api.SSHKey, data *models.ClickPipeSSHKeyResourceModel) {
	data.ID = types.StringValue(sshKey.ID)
	data.ServiceID = types.StringValue(serviceID)
	data.Name = types.StringValue(sshKey.Name)
	data.Description = types.StringValue(sshKey.Description)
	data.Host = types.StringValue(sshKey.Host)
	data.Username = types.StringValue(sshKey.Username)
	data.PublicKey = types.StringValue(sshKey.PublicKey)
	data.Status = types.StringValue(sshKey.Status)
	data.StatusMessage = types.StringValue(sshKey.StatusMessage)
	data.CreatedAt = types.StringValue(sshKey.CreatedAt)
	data.UpdatedAt = types.StringValue(sshKey.UpdatedAt)

	if port, err := strconv.ParseInt(sshKey.Port, 10, 64); err == nil {
		data.Port = types.Int64Value(port)
	}

	if sshKey.LastValidatedAt != nil {
		data.LastValidatedAt = types.StringValue(*sshKey.LastValidatedAt)
	} else {
		data.LastValidatedAt = types.StringNull()
	}
}

func (r *ClickPipeSSHKeyResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var data models.ClickPipeSSHKeyResourceModel

	resp.Diagnostics.Append(req.Plan.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	serviceID := data.ServiceID.ValueString()

	createReq := api.CreateSSHKey{
		Name:        data.Name.ValueString(),
		Description: data.Description.ValueString(),
		Host:        data.Host.ValueString(),
		Port:        strconv.FormatInt(data.Port.ValueInt64(), 10),
		Username:    data.Username.ValueString(),
	}

	tflog.Debug(ctx, "Creating ClickPipe SSH key resource", map[string]interface{}{
		"service_id": serviceID,
		"name":       createReq.Name,
	})

	sshKey, err := r.client.CreateSSHKey(ctx, serviceID, createReq)
	if err != nil {
		resp.Diagnostics.AddError("Error creating ClickPipe SSH key resource", err.Error())
		return
	}

	applySSHKeyToModel(serviceID, sshKey, &data)

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

func (r *ClickPipeSSHKeyResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var data models.ClickPipeSSHKeyResourceModel

	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	serviceID := data.ServiceID.ValueString()
	sshKeyID := data.ID.ValueString()

	tflog.Debug(ctx, "Reading ClickPipe SSH key resource", map[string]interface{}{
		"service_id": serviceID,
		"ssh_key_id": sshKeyID,
	})

	sshKey, err := r.client.GetSSHKey(ctx, serviceID, sshKeyID)
	if err != nil {
		if api.IsNotFound(err) {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Error reading ClickPipe SSH key resource", err.Error())
		return
	}

	applySSHKeyToModel(serviceID, sshKey, &data)

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

